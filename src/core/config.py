"""YAML configuration loader with platform auto-detection.

Configuration is assembled from layers, lowest priority first:

1. **Base YAML** (``--config``, e.g. ``config/bcm_config_test.yaml``) —
   tracked in git and *never written* by BCM. Keeping it pristine is what
   lets ``git pull`` update the car without merge conflicts, and keeps the
   comments in it.
2. **Local overlay** (``local_path``, normally ``config/local.yaml``) —
   git-ignored, written by :meth:`BCMConfig.save` as the *difference*
   against the base (atomically, mode 0600). Runtime choices made in the UI
   (theme, module toggles, last Bluetooth device …) end up here. The header
   records the base file name; under a different base the overlay is still
   applied but never rewritten (see ``BCMConfig._check_overlay_base``).
3. **Secrets from the environment** (:data:`SECRET_ENV_MAP`) — on the car
   systemd loads them from ``/etc/bcm/bcm.env``; on a laptop a repo-level
   ``.env`` works too (the real environment wins). They are never written
   to the overlay, so an API key cannot leak into a file by accident.
4. **Platform resolution** (``system.platform``) — never persisted either.

Backwards compatibility: ``BCMConfig()`` / ``BCMConfig(platform_override=...)``
/ ``BCMConfig(config_path=...)`` behave as before — without ``local_path``
there is no overlay and without ``env``/``dotenv_path`` no secrets are
injected. The only behavioural change for such callers is that ``save()``
no longer rewrites the base file (it logs and returns ``False``).
"""

