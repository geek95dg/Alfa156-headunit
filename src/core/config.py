#: Default file name of the local overlay, placed next to the base YAML.
LOCAL_CONFIG_NAME = "local.yaml"

#: Secret config values and the environment variables that provide them.
#: Only non-empty values are applied. A value coming from the environment is
#: never written to the local overlay (env stays the single source).
SECRET_ENV_MAP: dict[str, str] = {
    "weather.api_key": "BCM_OWM_API_KEY",
    "travel.openrouteservice_key": "BCM_ORS_API_KEY",
    "travel.tomtom_key": "BCM_TOMTOM_API_KEY",
    "wifi.password": "BCM_WIFI_PASSWORD",
    "wifi.alfa_net.password": "BCM_ALFA_NET_PASSWORD",
    # HMAC secret shared with the Termux agent on the car phone
    # (src/network/car_phone_agent.py) — env only, never local.yaml.
    "network.car_phone.agent.secret": "BCM_CAR_PHONE_AGENT_SECRET",
}

#: Dot-paths that are never persisted, whatever their value.
NEVER_PERSIST_PATHS = frozenset({"system.platform"})

#: Any key (at any depth) whose name ends with this suffix is runtime state
#: (e.g. ``wifi.password_runtime`` — the Wi-Fi Direct PSK regenerated for
#: every P2P group) and is never persisted.
RUNTIME_SUFFIX = "_runtime"

#: First line of every overlay BCM writes.
LOCAL_HEADER = "# Generated by BCM — do not commit\n"

#: Second header line: the base YAML the overlay is a difference against.
#: The overlay sits next to its base, so bcm_config.yaml, bcm_config_test.yaml
#: and the rollback target bcm_config_temp.yaml all share config/local.yaml.
#: Saving it against a *different* base than it was written for would drop
#: every override that happens to equal that base — rolling back and forth
#: would then silently lose settings. See BCMConfig._check_overlay_base.
BASE_MARKER = "# base: "

#: The overlay can hold the Wi-Fi password and the paired phone's address.
LOCAL_FILE_MODE = 0o600

#: How many ``local.yaml.broken-<ts>`` copies are kept for post-mortem.
BROKEN_KEEP = 3

_ENV_NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
# Conservative on purpose: the name goes into a YAML comment line, so
# anything that could end the line or the comment is not recorded at all.
_BASE_NAME_RE = re.compile(r"^[A-Za-z0-9._-]{1,128}$")
_BASE_LINE_RE = re.compile(r"^# base: ([A-Za-z0-9._-]{1,128})\s*$")
_EXPORT_RE = re.compile(r"^export\s+")
_MISSING = object()


# ── Platform detection ────────────────────────────────────────────────────

def _detect_platform() -> str:
    """Detect whether we're running on x86, Orange Pi 5 Pro/Plus, or OPi PC.

    Detection order:
      1. armv7l with Allwinner H3 → opi_pc (Orange Pi PC 1.2, bench rig)
      2. aarch64 (RK3588 / RK3588S / etc.) → opi (Orange Pi 5 Pro / 5 Plus,
         production)
      3. Fallback → x86 (development / simulation)
    """
    machine = platform.machine().lower()
    if machine in ("aarch64", "armv7l", "armv8l"):
        # Distinguish OPi PC (H3, armv7l) from OPi 5 Pro / 5 Plus (aarch64)
        if machine == "armv7l" and _is_allwinner_h3():
            return "opi_pc"
        return "opi"
    return "x86"


def _is_allwinner_h3() -> bool:
    """Check if running on Allwinner H3 SoC (Orange Pi PC / PC Plus / One)."""
    try:
        dt_model = Path("/proc/device-tree/model")
        if dt_model.exists():
            model = dt_model.read_text().lower()
            if "orange pi pc" in model or "sun8i-h3" in model:
                return True
        # Fallback: check /proc/cpuinfo for sun8i
        cpuinfo = Path("/proc/cpuinfo")
        if cpuinfo.exists():
            text = cpuinfo.read_text().lower()
            if "sun8i" in text or "allwinner" in text:
                return True
    except Exception:
        pass
    return False


# ── Pure helpers (shared with tools/migrate_local_config.py) ──────────────

def _deep_merge(base: dict, override: dict) -> dict:
    """Recursively merge override into base, returning a new dict.

    Dicts merge key by key; any other value (lists included) is replaced
    as a whole.
    """
    result = copy.deepcopy(base)
    for key, value in override.items():
        if key in result and isinstance(result[key], dict) and isinstance(value, dict):
            result[key] = _deep_merge(result[key], value)
        else:
            result[key] = copy.deepcopy(value)
    return result


def get_path(data: Mapping, dotpath: str, default: Any = None) -> Any:
    """Read ``a.b.c`` from nested dicts; ``default`` when any part is missing."""
    node: Any = data
    for key in dotpath.split("."):
        if isinstance(node, dict) and key in node:
            node = node[key]
        else:
            return default
    return node


def set_path(data: dict, dotpath: str, value: Any) -> None:
    """Write ``a.b.c`` into nested dicts, creating (or replacing non-dict)
    intermediate nodes."""
    keys = dotpath.split(".")
    node = data
    for key in keys[:-1]:
        if key not in node or not isinstance(node[key], dict):
            node[key] = {}
        node = node[key]
    node[keys[-1]] = value


def compute_overlay(base: Mapping, current: Mapping) -> dict:
    """Return the part of ``current`` that differs from ``base``.

    Dicts are compared key by key (recursively); lists and scalars by
    equality, so a changed list is stored whole — exactly what
    :func:`_deep_merge` replaces on load. Keys missing from ``base`` are
    included. Keys *removed* from ``current`` cannot be expressed by an
    overlay and are ignored (the base value comes back on the next load).
    """
    out: dict = {}
    for key, value in current.items():
        if key not in base:
            out[key] = copy.deepcopy(value)
            continue
        base_value = base[key]
        if isinstance(value, dict) and isinstance(base_value, dict):
            sub = compute_overlay(base_value, value)
            if sub:
                out[key] = sub
        elif value != base_value:
            out[key] = copy.deepcopy(value)
    return out


def is_never_persisted(dotpath: str, secret_paths=()) -> bool:
    """True for config paths that must never be written to the overlay.

    That is ``system.platform`` (resolved at start-up), any key whose last
    segment ends with ``_runtime`` (live Wi-Fi Direct credentials and the
    like) and every path in ``secret_paths`` (values provided by env).
    """
    if dotpath in NEVER_PERSIST_PATHS or dotpath in secret_paths:
        return True
    return dotpath.rsplit(".", 1)[-1].endswith(RUNTIME_SUFFIX)


def prune_overlay(overlay: Mapping, secret_paths=(), _prefix: str = "") -> tuple[dict, list[str]]:
    """Remove never-persisted entries from ``overlay``.

    Returns ``(pruned_copy, dropped_dotpaths)``. A dict that becomes empty
    only because its children were dropped is removed too; a dict that was
    empty to begin with is kept.
    """
    out: dict = {}
    dropped: list[str] = []
    for key, value in overlay.items():
        dotpath = f"{_prefix}{key}"
        if is_never_persisted(dotpath, secret_paths):
            dropped.append(dotpath)
            continue
        if isinstance(value, dict):
            sub, sub_dropped = prune_overlay(value, secret_paths, f"{dotpath}.")
            dropped.extend(sub_dropped)
            if sub or not value:
                out[key] = sub
        else:
            out[key] = copy.deepcopy(value)
    return out, dropped


def iter_leaves(data: Mapping, _prefix: str = "") -> Iterator[tuple[str, Any]]:
    """Yield ``(dotpath, value)`` for every non-dict value (and empty dict)."""
    for key, value in data.items():
        dotpath = f"{_prefix}{key}"
        if isinstance(value, dict) and value:
            yield from iter_leaves(value, f"{dotpath}.")
        else:
            yield dotpath, value


def count_leaves(data: Mapping) -> int:
    """Number of individual overridden values in an overlay."""
    return sum(1 for _ in iter_leaves(data))


def to_plain(obj: Any) -> Any:
    """Normalise to what YAML round-trips: tuples become lists, recursively."""
    if isinstance(obj, dict):
        return {k: to_plain(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [to_plain(v) for v in obj]
    return obj


def render_overlay(overlay: Mapping, base_name: Optional[str] = None) -> str:
    """Serialise an overlay exactly the way :meth:`BCMConfig.save` writes it.

    Sorted keys make the output deterministic, so an unchanged overlay
    renders to identical text. ``base_name`` (file name of the base YAML)
    is recorded as a ``# base:`` header line when it is a plain file name.
    """
    header = LOCAL_HEADER
    if base_name and _BASE_NAME_RE.match(base_name):
        header += f"{BASE_MARKER}{base_name}\n"
    body = yaml.safe_dump(to_plain(dict(overlay)), sort_keys=True,
                          allow_unicode=True, default_flow_style=False)
    return header + body


def overlay_base_name(raw: bytes) -> Optional[str]:
    """Base file name recorded in an overlay's ``# base:`` header, or None.

    Only the leading comment block is looked at, so a ``# base:`` comment
    further down in a hand-edited file is not mistaken for the header.
    """
    for line in raw.decode("utf-8", "replace").splitlines():
        if not line.startswith("#"):
            break
        match = _BASE_LINE_RE.match(line)
        if match:
            return match.group(1)
    return None


def parse_dotenv(text: str) -> dict[str, str]:
    """Parse a ``.env`` / systemd ``EnvironmentFile`` style file.

    Supported, deliberately minimal (the same file must mean the same thing
    to systemd and to this parser): ``KEY=VALUE`` lines, whole-line comments
    starting with ``#`` or ``;``, an optional ``export `` prefix and an
    optional pair of matching single or double quotes around the value.
    There is no interpolation, no escape processing and no inline comment —
    ``KEY=abc # x`` yields ``abc # x``. Malformed lines are skipped.
    """
    result: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line[0] in "#;":
            continue
        line = _EXPORT_RE.sub("", line, count=1)
        key, sep, value = line.partition("=")
        if not sep:
            continue
        key = key.strip()
        if not _ENV_NAME_RE.match(key):
            continue
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
            value = value[1:-1]
        result[key] = value
    return result


def _read_overlay_file(path: Path) -> tuple[str, Optional[dict], str, bytes]:
    """Read and validate an overlay file.

    Returns ``(status, data, reason, raw)`` where status is ``"ok"``,
    ``"broken"`` (empty, not YAML, not a mapping, not UTF-8) or
    ``"unreadable"`` (I/O error — the content itself may be fine).

    "Empty" means what a power cut or truncation leaves behind: zero bytes,
    only whitespace, or NUL-filled blocks. A file that holds only comments
    (every override commented out by hand — the natural way to drop them)
    is a valid, *empty* overlay: treating it as broken would quarantine it
    and resurrect the older ``.bak`` behind the user's back.
    """
    try:
        raw = path.read_bytes()
    except OSError as e:
        return "unreadable", None, str(e), b""
    try:
        data = yaml.safe_load(raw.decode("utf-8"))
    except UnicodeDecodeError:
        return "broken", None, "not valid UTF-8", raw
    except yaml.YAMLError as e:
        first = str(e).strip().splitlines()[0] if str(e).strip() else type(e).__name__
        return "broken", None, f"YAML error: {first}", raw
    if data is None:
        if not raw.strip() or b"\0" in raw:
            return "broken", None, "empty file", raw
        return "ok", {}, "", raw      # comments only (or an explicit `~`)
    if not isinstance(data, dict):
        return "broken", None, f"top level is a {type(data).__name__}, not a mapping", raw
    return "ok", data, "", raw


