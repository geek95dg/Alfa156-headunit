deep_merge = _deep_merge
read_overlay_file = _read_overlay_file


def resolve_base_path(config_path: Optional[str] = None,
                      platform_override: Optional[str] = None) -> Path:
    """Path of the base YAML that :class:`BCMConfig` would load."""
    if config_path:
        return Path(config_path)
    return BCMConfig._pick_default_config(platform_override)


def default_local_path(base_path: Path) -> Path:
    """Default overlay location: ``local.yaml`` next to the base YAML."""
    return Path(base_path).parent / LOCAL_CONFIG_NAME


# ── BCMConfig ─────────────────────────────────────────────────────────────

class BCMConfig:
    """Loads and provides access to the BCM configuration.

    Usage:
        cfg = BCMConfig()                           # auto-detect platform
        cfg = BCMConfig(platform_override="x86")    # force platform
        cfg = BCMConfig(config_path="other.yaml")   # custom config file
        cfg = BCMConfig(config_path="config/bcm_config_test.yaml",
                        local_path="config/local.yaml",
                        env=os.environ, dotenv_path=".env")  # what main.py does

        value = cfg.get("display.dashboard.width")  # dot-notation access
        value = cfg["display"]["dashboard"]["width"] # dict-style access

    Attributes:
        config_path: resolved path of the base YAML (never written).
        local_path: path of the local overlay, or ``None`` (saving disabled).
        platform: resolved ``system.platform``.
        secret_sources: dot-path → name of the env variable that provided it.
        load_warnings: human-readable problems found while loading (broken
            overlay recovered from backup, unreadable ``.env`` …). main.py
            logs them once logging is configured.

    Thread safety: ``set()``/``save()`` are serialised by a lock. ``get()``
    returns *live* references (callers such as the SWC learn mode mutate
    the returned dict in place and rely on that), so ``save()`` copies the
    data under the lock and retries once if a concurrent in-place mutation
    interrupts the copy.
    """

    def __init__(
        self,
        config_path: Optional[str] = None,
        platform_override: Optional[str] = None,
        *,
        local_path: Optional[os.PathLike | str] = None,
        env: Optional[Mapping[str, str]] = None,
        dotenv_path: Optional[os.PathLike | str] = None,
    ):
        self._lock = threading.RLock()
        # Separate lock for the snapshot→write sequence: two concurrent
        # saves must not land on disk in the opposite order of their
        # snapshots, but set() must not wait for an fsync either.
        self._write_lock = threading.Lock()
        self.load_warnings: list[str] = []
        self.secret_sources: dict[str, str] = {}
        self._secret_values: dict[str, Any] = {}
        self._warned_secrets: set[str] = set()
        self._warned_no_local = False
        # Overlay content currently on disk (as plain data), used to skip
        # rewriting an identical file. None = unknown → next save writes.
        self._last_overlay: Optional[dict] = None
        self._save_disabled_reason = ""
        self._warned_save_disabled = False

        path = resolve_base_path(config_path, platform_override)
        if not path.exists():
            raise FileNotFoundError(f"Config file not found: {path}")

        with open(path, "r", encoding="utf-8") as f:
            base = yaml.safe_load(f) or {}
        if not isinstance(base, dict):
            raise ValueError(f"Config root must be a mapping: {path}")
        # Pristine copy of the base file. Never handed out and never
        # mutated: _deep_merge deep-copies it, so in-place edits of live
        # references obtained via get() cannot leak back into it.
        self._base: dict = base
        self.config_path: Path = path.resolve()
        self.local_path: Optional[Path] = (
            Path(os.path.abspath(os.fspath(local_path))) if local_path else None
        )
        if self.local_path is not None and self.local_path == self.config_path:
            # Writing the overlay over the base would destroy it.
            self._warn(f"local overlay path equals the base config ({self.local_path}) "
                       "— local overlay disabled")
            self.local_path = None

        local = self._load_local() if self.local_path is not None else {}
        data = _deep_merge(base, local)
        self._apply_secrets(data, env, dotenv_path)

        # Resolve platform
        system = data.get("system")
        if not isinstance(system, dict):
            system = {}
            data["system"] = system
        if platform_override:
            system["platform"] = platform_override
        elif system.get("platform") in ("auto", None):
            system["platform"] = _detect_platform()

        self._data: dict = data
        self.platform: str = system["platform"]

    # ── Loading ───────────────────────────────────────────────────────

    def _warn(self, message: str) -> None:
        """Record a load-time problem.

        Logged at INFO here (logging is usually not configured yet while the
        config loads); main.py re-logs ``load_warnings`` as WARNINGs.
        """
        self.load_warnings.append(message)
        log.info("config: %s", message)

    def _load_local(self) -> dict:
        """Load the local overlay with fallback to its backup.

        missing or comments only → fine (empty overlay); empty (0 bytes,
        whitespace, NULs) / not YAML / not a mapping →
        quarantined as ``local.yaml.broken-<ts>`` and ``local.yaml.bak`` is
        tried (and restored as ``local.yaml`` when good); both unusable →
        base config only, plus a load warning. Never raises for a bad file:
        a typo in the overlay must not keep BCM from booting.
        """
        p = self.local_path
        assert p is not None
        cleanup_stale_tmp(p.parent, f".{p.name}.")
        self._last_overlay = {}
        if not p.exists():
            return {}

        status, data, reason, raw = _read_overlay_file(p)
        if status == "ok":
            self._check_overlay_base(raw, p)
            data = self._sanitize_local(data, p)
            self._last_overlay = to_plain(data)
            return data
        if status == "unreadable":
            # Do not quarantine or overwrite a file we merely failed to
            # read — its content may be perfectly good.
            self._save_disabled_reason = f"{p} unreadable ({reason})"
            self._warn(f"local overlay {p} unreadable ({reason}) — using base config "
                       "only; saving disabled")
            self._last_overlay = None
            return {}

        moved = self._quarantine(p)
        msg = f"local overlay {p} is broken ({reason})"
        if moved is not None:
            msg += f", moved to {moved.name}"
        bak = p.with_name(p.name + ".bak")
        if bak.exists():
            b_status, b_data, b_reason, b_raw = _read_overlay_file(bak)
            if b_status == "ok":
                restored = False
                try:
                    atomic_write_bytes(p, b_raw, mode=LOCAL_FILE_MODE)
                    restored = True
                except OSError as e:
                    msg += f" (restoring {bak.name} failed: {e})"
                self._warn(f"{msg}; recovered from {bak.name}")
                self._check_overlay_base(b_raw, bak)
                b_data = self._sanitize_local(b_data, bak)
                self._last_overlay = to_plain(b_data) if restored else None
                return b_data
            msg += f"; backup {bak.name} unusable too ({b_reason})"
        self._warn(f"{msg} — using base config only")
        self._last_overlay = {} if moved is not None else None
        return {}

    def _check_overlay_base(self, raw: bytes, origin: Path) -> None:
        """Freeze an overlay that was written against a different base YAML.

        Its overrides are still applied (they are absolute values, so they
        mean the same over any base), but saving is disabled: a save would
        store the difference against *this* base and drop every override
        that happens to equal it — after a rollback to bcm_config_temp.yaml
        and back, those settings would be gone. An overlay without the
        ``# base:`` line (hand-written, older) is adopted as is.
        """
        recorded = overlay_base_name(raw)
        current = self.config_path.name
        if recorded is None or recorded == current:
            return
        self._save_disabled_reason = (f"{origin.name} holds overrides for base {recorded}, "
                                      f"but BCM runs with {current}")
        self._warn(f"{origin.name} was written for base config {recorded} but BCM runs "
                   f"with {current} — its overrides are applied, but saving is disabled "
                   f"so they are not rewritten against the wrong base. To save changes "
                   f"for {current}, point BCM_LOCAL_CONFIG / --local-config at a separate "
                   f"file, or delete the '{BASE_MARKER.strip()}' line in {origin.name} "
                   f"to adopt it")

    def _sanitize_local(self, local: dict, origin: Path) -> dict:
        """Ignore overlay values that would replace a whole base section.

        Commenting out every child of a section in a hand-edited overlay
        leaves ``audio:`` = null behind, which would otherwise wipe the
        whole ``audio`` block of the base config. Likewise a scalar or list
        typed where the base has a section (``weather: true`` instead of
        ``modules.weather: true``) would replace it, and code doing
        ``config.get("weather", {}).get(...)`` would crash on the bool.
        Such keys are skipped with a load warning.
        """
        def walk(node: dict, base: Any, prefix: str) -> dict:
            out = {}
            for key, value in node.items():
                base_value = base.get(key) if isinstance(base, dict) else None
                if isinstance(base_value, dict) and not isinstance(value, dict):
                    if value is None:
                        self._warn(f"{origin.name}: '{prefix}{key}' is empty — ignored "
                                   "(would erase the whole section)")
                    else:
                        self._warn(f"{origin.name}: '{prefix}{key}' is a "
                                   f"{type(value).__name__}, but the base config has a "
                                   "section there — ignored")
                    continue
                if isinstance(value, dict):
                    out[key] = walk(value, base_value, f"{prefix}{key}.")
                else:
                    out[key] = value
            return out
        return walk(local, self._base, "")

    def _quarantine(self, path: Path) -> Optional[Path]:
        """Rename a broken overlay aside, keeping the newest BROKEN_KEEP copies."""
        stamp = time.strftime("%Y%m%d-%H%M%S")
        dest = path.with_name(f"{path.name}.broken-{stamp}")
        n = 1
        while dest.exists():
            dest = path.with_name(f"{path.name}.broken-{stamp}-{n}")
            n += 1
        try:
            os.replace(path, dest)
        except OSError as e:
            self._warn(f"could not move broken {path.name} aside: {e}")
            return None
        fsync_dir(path.parent)

        prefix = f"{path.name}.broken-"
        try:
            copies = sorted(q for q in path.parent.iterdir()
                            if q.name.startswith(prefix) and q.is_file())
        except OSError:
            copies = []
        for old in copies[:-BROKEN_KEEP]:
            if old == dest:
                continue
            try:
                old.unlink()
            except OSError:
                pass
        return dest

    def _read_dotenv(self, path: Path) -> dict[str, str]:
        try:
            st = path.stat()
        except FileNotFoundError:
            return {}
        except OSError as e:
            self._warn(f"cannot read {path}: {e}")
            return {}
        if st.st_mode & 0o077:
            self._warn(f"{path} is readable by group/others — run: chmod 600 {path}")
        try:
            return parse_dotenv(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError) as e:
            self._warn(f"cannot read {path}: {e}")
            return {}

    def _apply_secrets(self, data: dict, env: Optional[Mapping[str, str]],
                       dotenv_path: Optional[os.PathLike | str]) -> None:
        """Inject SECRET_ENV_MAP values; the real environment wins over .env.

        Precedence is per variable and only non-empty values count, so an
        empty ``BCM_OWM_API_KEY=`` line in bcm.env does not mask a key set
        in a developer's ``.env``.
        """
        if env is None and dotenv_path is None:
            return
        dotenv = self._read_dotenv(Path(dotenv_path)) if dotenv_path is not None else {}
        sources = (env or {}, dotenv)
        for dotpath, var in SECRET_ENV_MAP.items():
            for source in sources:
                value = source.get(var)
                if isinstance(value, str) and value.strip():
                    set_path(data, dotpath, value)
                    self.secret_sources[dotpath] = var
                    self._secret_values[dotpath] = value
                    break

    @staticmethod
    def _pick_default_config(platform_override: Optional[str]) -> Path:
        """No --config given: pick the YAML matching the platform.

        A bench rig booted without --config used to silently load the
        x86-targeted bcm_config.yaml (wrong GPIO/serial values). Now the
        opi_pc-specific file is selected automatically when the hardware
        (or an explicit override) says opi_pc.

        The OPi PC bench rig was retired when the build moved to the
        Lenovo M910q, so its YAML now lives in Archive/orange-pi-pc/.
        Both locations are probed — config/ first, so restoring the file
        to its old home keeps working — and the archived rig still boots
        without having to un-archive anything.
        """
        plat = platform_override or _detect_platform()
        if plat == "opi_pc":
            repo_root = DEFAULT_CONFIG_PATH.parent.parent
            candidates = (
                DEFAULT_CONFIG_PATH.parent / "bcm_config_opi_pc.yaml",
                repo_root / "Archive" / "orange-pi-pc" / "bcm_config_opi_pc.yaml",
            )
            for candidate in candidates:
                if candidate.exists():
                    return candidate
        return DEFAULT_CONFIG_PATH

    # ── Access ────────────────────────────────────────────────────────

    def get(self, dotpath: str, default: Any = None) -> Any:
        """Access a nested config value using dot notation.

        Returns the live object (not a copy) for dicts and lists.

        Example: cfg.get("display.dashboard.width") -> 800
        """
        return get_path(self._data, dotpath, default)

    def set(self, dotpath: str, value: Any) -> None:
        """Set a nested config value using dot notation (in memory; call
        :meth:`save` to persist it to the local overlay)."""
        with self._lock:
            set_path(self._data, dotpath, value)

    def _snapshot(self) -> dict:
        """Deep copy of the live data, taken under the lock.

        In-place mutations through references returned by get() do not take
        the lock; if one changes a dict's size mid-copy, deepcopy raises
        RuntimeError — retry once, a second collision propagates.
        """
        with self._lock:
            try:
                return copy.deepcopy(self._data)
            except RuntimeError:
                return copy.deepcopy(self._data)

    def overlay(self) -> dict:
        """What :meth:`save` would persist: the difference against the base,
        without platform, ``*_runtime`` and env-provided secrets."""
        overlay, _dropped = prune_overlay(compute_overlay(self._base, self._snapshot()),
                                          self.secret_sources)
        return overlay

    # ── Saving ────────────────────────────────────────────────────────

    def save(self, path: Optional[str] = None) -> bool:
        """Persist runtime changes to the local overlay.

        Writes only the difference against the base YAML; the base file is
        never touched. If the rendered overlay equals what is already on
        disk nothing is written, so frequent callers (every Bluetooth
        connect) cost nothing. Otherwise the previous good file is copied to
        ``local.yaml.bak`` and the new one is written atomically with mode
        0600.

        Args:
            path: Kept only for signature compatibility — no caller passes
                it. Writing the full merged config to an arbitrary file is
                what used to strip comments and leak ``*_runtime`` values and
                API keys into tracked YAMLs, so an explicit path is refused
                (logged, returns ``False``).

        Returns:
            ``True`` when the overlay on disk matches the in-memory state
            (written now or already up to date), ``False`` when nothing was
            persisted (no ``local_path``, refused path, or an error — logged).
            Expected errors are never raised: a failing save must not take
            down a Bluetooth or UI handler.
        """
        if path is not None:
            log.error("BCMConfig.save(path=%s) is not supported — runtime changes go to "
                      "the local overlay only (%s)", path, self.local_path)
            return False
        if self.local_path is None:
            if not self._warned_no_local:
                self._warned_no_local = True
                log.warning("Config change not persisted: no local overlay configured "
                            "(base %s is never written)", self.config_path)
            else:
                log.debug("Config change not persisted (no local overlay)")
            return False
        if self._save_disabled_reason:
            # Once at WARNING, then DEBUG: save() runs on every Bluetooth
            # connect and the reason does not change until restart.
            if not self._warned_save_disabled:
                self._warned_save_disabled = True
                log.warning("Config change not persisted: %s", self._save_disabled_reason)
            else:
                log.debug("Config change not persisted: %s", self._save_disabled_reason)
            return False

        with self._write_lock:
            try:
                snapshot = self._snapshot()
            except RuntimeError as e:
                log.error("Config save skipped — data changed during copy: %s", e)
                return False
            overlay, _dropped = prune_overlay(compute_overlay(self._base, snapshot),
                                              self.secret_sources)
            self._warn_changed_secrets(snapshot)
            plain = to_plain(overlay)

            exists = self.local_path.exists()
            if plain == self._last_overlay and (exists or not plain):
                return True
            if not plain and not exists:
                # Nothing overridden and no file yet — do not create one.
                self._last_overlay = {}
                return True
            try:
                text = render_overlay(plain, base_name=self.config_path.name)
            except Exception as e:  # unserialisable value set by some module
                log.error("Config save failed — overlay cannot be serialised: %s", e)
                return False
            if exists:
                self._backup_current()
            try:
                atomic_write_text(self.local_path, text, mode=LOCAL_FILE_MODE)
            except OSError as e:
                log.error("Config save to %s failed: %s", self.local_path, e)
                return False
            self._last_overlay = plain
            log.info("Config overlay saved: %d override(s) → %s",
                     count_leaves(plain), self.local_path)
            return True

    def _backup_current(self) -> None:
        """Copy the current overlay to ``.bak`` if it is valid.

        A broken current file is not backed up — that would replace the last
        good backup with garbage. Failure here does not block the save.
        """
        p = self.local_path
        assert p is not None
        bak = p.with_name(p.name + ".bak")
        status, _data, reason, raw = _read_overlay_file(p)
        if status != "ok":
            log.warning("Not backing up %s (%s) — keeping previous %s", p.name, reason, bak.name)
            return
        try:
            atomic_write_bytes(bak, raw, mode=LOCAL_FILE_MODE)
        except OSError as e:
            log.warning("Backup of %s to %s failed: %s", p.name, bak.name, e)

    def _changed_secret_paths(self, data: Mapping) -> list[str]:
        """Env-provided secret paths whose value in ``data`` differs from env."""
        return [dotpath for dotpath in self.secret_sources
                if get_path(data, dotpath, _MISSING) != self._secret_values.get(dotpath)]

    def unpersisted_secret_changes(self) -> list[str]:
        """Dot-paths of env-provided secrets that were changed at runtime.

        Such a value is in effect now but is never written to the overlay
        (env stays the single source), so it reverts on the next restart.
        The Settings UI uses this to say "managed by /etc/bcm/bcm.env"
        instead of a misleading "Saved".
        """
        with self._lock:
            return self._changed_secret_paths(self._data)

    def _warn_changed_secrets(self, snapshot: dict) -> None:
        """Env-provided secrets are not persisted; say so (once per key) when
        something changed one at runtime, e.g. Wi-Fi password in the UI."""
        for dotpath in self._changed_secret_paths(snapshot):
            var = self.secret_sources[dotpath]
            if dotpath not in self._warned_secrets:
                self._warned_secrets.add(dotpath)
                log.warning("%s was changed at runtime but is provided by env %s — the new "
                            "value lasts until restart; update %s in bcm.env to keep it",
                            dotpath, var, var)

    # ── Misc ──────────────────────────────────────────────────────────

    def is_module_enabled(self, module_name: str) -> bool:
        """Check if a module is enabled in the config.

        Reads ``modules.<name>``. Falls back to the legacy
        ``modules_v85.<name>`` block (pre-v8.5.2 configs kept the v8.5
        modules there, but no code ever read it — so alarm, crash_detect,
        battery etc. were silently disabled). ``battery`` was historically
        spelled ``battery_backup`` in that block.
        """
        val = self.get(f"modules.{module_name}")
        if val is None:
            legacy_name = {"battery": "battery_backup"}.get(module_name, module_name)
            val = self.get(f"modules_v85.{legacy_name}")
        return bool(val)

    @property
    def data(self) -> dict:
        """Return the raw config dict (read-only copy)."""
        return self._snapshot()

    def __getitem__(self, key: str) -> Any:
        return self._data[key]

    def __contains__(self, key: str) -> bool:
        return key in self._data

    def __repr__(self) -> str:
        return (f"BCMConfig(platform={self.platform!r}, path={self.config_path}, "
                f"local={self.local_path})")
