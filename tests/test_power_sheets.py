"""Guards for the power sheets redrawn for the current design (22.11.2026).

Six sheets (``charging_lvd``, ``power_domains_m910q``, ``wiring_power_modules``,
``power_test_build``, ``schematic_test_build``, ``wiring_test_build``) are
now generated by ``schematics/gen_*.py``; ``power_buffered_m910q`` and
``vehicle_layout_m910q`` are hand-drawn. All eight must:

* be well-formed XML with a non-empty ``<title>``,
* show none of the retired hardware of the previous design (XL6019 / XL4016
  converters, MBR2045 / MBR2545CT diodes, copper bus bars instead of the
  bank on cable, a series NTC on the step-up output).

When ``cairosvg`` (and Pillow, for the 600 dpi etch print) is importable,
``render_png.py --check`` must also report every PNG in ``schematics/png/``
as current. CI does not install cairosvg, so there the check is skipped.

The checks only read files; nothing is written anywhere.
"""

from __future__ import annotations

import html
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
SCHEMATICS = REPO / "schematics"

REDRAWN_SVGS = [SCHEMATICS / f"{name}.svg" for name in (
    "charging_lvd",
    "power_domains_m910q",
    "wiring_power_modules",
    "power_test_build",
    "schematic_test_build",
    "wiring_test_build",
)]
HAND_DRAWN_SVGS = [
    SCHEMATICS / "power_buffered_m910q.svg",
    SCHEMATICS / "vehicle_layout_m910q.svg",
]
ALL_SVGS = REDRAWN_SVGS + HAND_DRAWN_SVGS

RETIRED = {
    "XL6019": re.compile(r"XL\s*6019", re.I),
    "XL4016": re.compile(r"XL\s*4016", re.I),
    "MBR2045": re.compile(r"MBR\s*2045", re.I),
    "MBR2545CT": re.compile(r"MBR\s*2545", re.I),
    "listwa miedziana": re.compile(
        r"listw\w*\s+(?:z\s+)?miedz|szyn\w*\s+(?:Cu\b|miedzian)|płaskownik", re.I),
    # "Nie ma w torze: … ani termistora szeregowego" is a negation, not a part.
    "szeregowy NTC": re.compile(r"\bNTC\b|(?<!ani )(?<!bez )\btermistor", re.I),
}

SVG_NS = "{http://www.w3.org/2000/svg}"


def _texts(path: Path) -> str:
    """Everything a reader sees: <text>/<tspan> content and <title>."""
    raw = path.read_text(encoding="utf-8")
    parts = re.findall(r"<(?:text|title)\b[^>]*>(.*?)</(?:text|title)>", raw, re.S)
    return "\n".join(html.unescape(re.sub(r"<[^>]+>", "", p)) for p in parts)


@pytest.mark.parametrize("path", ALL_SVGS, ids=lambda p: p.name)
def test_sheet_is_wellformed_with_title(path):
    root = ET.parse(path).getroot()
    assert root.tag == f"{SVG_NS}svg", f"{path.name}: korzeń to nie <svg>"
    title = root.find(f"{SVG_NS}title")
    assert title is not None and (title.text or "").strip(), \
        f"{path.name}: brak <title> jako pierwszego poziomu"


@pytest.mark.parametrize("path", ALL_SVGS, ids=lambda p: p.name)
def test_sheet_shows_no_retired_parts(path):
    text = _texts(path)
    assert text.strip(), f"{path.name}: brak napisów"
    bad = [name for name, rx in RETIRED.items() if rx.search(text)]
    assert not bad, f"{path.name}: wycofany sprzęt na rysunku: {bad}"


@pytest.mark.parametrize("path", REDRAWN_SVGS, ids=lambda p: p.name)
def test_redrawn_sheet_has_generator(path):
    gen = SCHEMATICS / f"gen_{path.stem}.py"
    assert gen.is_file(), f"{path.name}: brak generatora {gen.name}"
    assert path.name in gen.read_text(encoding="utf-8"), \
        f"{gen.name} nie wskazuje na {path.name}"


def test_render_png_check_passes():
    pytest.importorskip("cairosvg")
    pytest.importorskip("PIL")
    proc = subprocess.run(
        [sys.executable, str(SCHEMATICS / "render_png.py"), "--check"],
        cwd=REPO, capture_output=True, text=True, timeout=600,
    )
    assert proc.returncode == 0, \
        f"render_png.py --check: PNG nieaktualne\n{proc.stdout}\n{proc.stderr}"
